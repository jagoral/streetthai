import type { ProductDoc } from "./linear-documents.parse.ts";

export const indexFileName = "README.md";

export function renderMirror(docs: readonly ProductDoc[]): Map<string, string> {
  const taken = new Set([slugify(indexFileName.replace(/\.md$/, ""))]);
  const entries = docs.toSorted(byTitleThenSlugId).map((doc) => {
    const base = slugify(doc.title);
    const slug = base === "" || taken.has(base) ? slugify(`${base}-${doc.slugId}`) : base;
    taken.add(slug);
    return { doc, fileName: `${slug}.md` };
  });

  const files = new Map<string, string>([[indexFileName, renderIndex(entries)]]);
  for (const { doc, fileName } of entries) {
    files.set(fileName, renderDoc(doc));
  }
  return files;
}

type Entry = { doc: ProductDoc; fileName: string };

function renderIndex(entries: readonly Entry[]): string {
  const rows = entries.map(
    ({ doc, fileName }) =>
      `| ${doc.title.replaceAll("|", "\\|")} | [${fileName}](${fileName}) | [Open](${doc.url}) | ${doc.updatedAt} |`,
  );
  return [
    "# Product docs mirror",
    "",
    "Generated by `pnpm product:pull` from the Linear project StreetThai; do not edit, re-run the script instead.",
    "",
    "| Title | Local file | Linear | Updated |",
    "| :--- | :--- | :--- | :--- |",
    ...rows,
    "",
  ].join("\n");
}

function renderDoc(doc: ProductDoc): string {
  const header = `> Mirrored from [Linear](${doc.url}), updated ${doc.updatedAt}.`;
  return `${header}\n\n${doc.content.trimEnd()}\n`;
}

function byTitleThenSlugId(a: ProductDoc, b: ProductDoc): number {
  return compare(a.title, b.title) || compare(a.slugId, b.slugId);
}

function compare(a: string, b: string): number {
  if (a === b) {
    return 0;
  }
  return a < b ? -1 : 1;
}

function slugify(title: string): string {
  return title
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
