import { expect, test } from "vitest";
import { renderMirror } from "../render-mirror.ts";

const overview = {
  title: "Product Vision 00 - Overview",
  slugId: "a1b2c3",
  url: "https://linear.app/acme/document/product-vision-00-overview-a1b2c3",
  updatedAt: "2026-11-10T09:00:00.000Z",
  content: "# Overview\n\nBody.",
};

test("each document becomes a kebab-case markdown file headed by its Linear URL and update time", () => {
  const files = renderMirror([overview]);

  expect(files.get("product-vision-00-overview.md")).toBe(
    "> Mirrored from [Linear](https://linear.app/acme/document/product-vision-00-overview-a1b2c3), updated 2026-11-10T09:00:00.000Z.\n\n# Overview\n\nBody.\n",
  );
});

test("titles that slug to nothing, to the index name, or to a taken name get their slugId appended", () => {
  const files = renderMirror(
    [
      ["Café | Notes", "s1"],
      ["cafe notes", "s2"],
      ["ภาษาไทย", "s3"],
      ["Readme", "s4"],
    ].map(([title = "", slugId = ""]) => ({ ...overview, title, slugId })),
  );

  expect(new Set(files.keys())).toEqual(
    new Set(["README.md", "cafe-notes.md", "cafe-notes-s2.md", "s3.md", "readme-s4.md"]),
  );
  expect(files.get("README.md")).toContain("| Café \\| Notes | [cafe-notes.md](cafe-notes.md) |");
});

test("README.md indexes every document by title and says the folder is generated", () => {
  const archive = {
    title: "Archive (v13) - Lean Business Plan & MVP PRD",
    slugId: "d4e5f6",
    url: "https://linear.app/acme/document/archive-d4e5f6",
    updatedAt: "2026-11-01T12:30:00.000Z",
    content: "Old draft.",
  };

  const files = renderMirror([overview, archive]);

  expect([...files.keys()]).toEqual([
    "README.md",
    "archive-v13-lean-business-plan-mvp-prd.md",
    "product-vision-00-overview.md",
  ]);
  expect(files.get("README.md")).toBe(
    [
      "# Product docs mirror",
      "",
      "Generated by `pnpm product:pull` from the Linear project StreetThai; do not edit, re-run the script instead.",
      "",
      "| Title | Local file | Linear | Updated |",
      "| :--- | :--- | :--- | :--- |",
      "| Archive (v13) - Lean Business Plan & MVP PRD | [archive-v13-lean-business-plan-mvp-prd.md](archive-v13-lean-business-plan-mvp-prd.md) | [Open](https://linear.app/acme/document/archive-d4e5f6) | 2026-11-01T12:30:00.000Z |",
      "| Product Vision 00 - Overview | [product-vision-00-overview.md](product-vision-00-overview.md) | [Open](https://linear.app/acme/document/product-vision-00-overview-a1b2c3) | 2026-11-10T09:00:00.000Z |",
      "",
    ].join("\n"),
  );
});
